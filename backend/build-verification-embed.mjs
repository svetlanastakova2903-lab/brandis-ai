import fs from 'node:fs';
const folder=new URL('../frontend/',import.meta.url);
const source=fs.readFileSync(new URL('verification-panel.html',folder),'utf8');
const script=source.match(/<script>([\s\S]*?)<\/script>/)[1].trim();
const html=source.replace(/<script>[\s\S]*?<\/script>/,'');
const output=`// Generated by backend/build-verification-embed.mjs; edit verification-panel.html.
(()=>{
 const start=async()=>{
  if(document.getElementById('brandis-verification'))return;
  const api=window.BRANDIS_API_URL||'https://brandis-ai.onrender.com';
  try{const response=await fetch(api+'/api/features');if(!response.ok || !(await response.json()).verification)return;}catch{return;}
  const mount=document.getElementById('cabinet');if(!mount)return;
  const wrapper=document.createElement('div');wrapper.innerHTML=${JSON.stringify(html)};mount.append(wrapper);
  ${script}
 };
 if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',start,{once:true});else start();
})();
`;
fs.writeFileSync(new URL('verification-embed.js',folder),output);
